/* Client contract checks against an isolated in-memory PHP-response fixture. No real accounts or business records. */
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
let checks = 0;
const check = (actual, expected, message) => { assert.deepEqual(actual, expected, message); checks++; };

(async () => {
  globalThis.window = new EventTarget();
  const forbidden = new Proxy({}, { get() { throw new Error('Browser-persistent storage must never be accessed.'); } });
  globalThis.localStorage = forbidden; globalThis.sessionStorage = forbidden;
  const requests = [], events = [];
  window.addEventListener('vg:private-storage-error', event => events.push(event.detail.message));
  const state = { user: { id: 's' + '1'.repeat(24), name: 'SDK Testi', email: 'sdk@example.invalid', role: 'payroll', approved: true, can_access_bordro: true },
    storage: { favoriteProducts: '["ilk"]' }, csrf: 'a'.repeat(64), active: true, failure: null, deferred: null };
  const catalog = { historicalInvoice1: [], historicalInvoice2: [], cablePrices: [], packages: [] };
  function reply(status, body) { return new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } }); }
  globalThis.fetch = async (url, options) => {
    const action = new URL(url, 'http://fixture.invalid').searchParams.get('action');
    const body = options.body ? JSON.parse(options.body) : null;
    requests.push({ url, options, action, body });
    const api = url.startsWith('/api/staff.php') ? 'vg-staff/1' : 'vg-company/1';
    if (!state.active) return reply(401, { api, ok: false, error: 'staff_login', message: 'Çalışan oturumu gerekiyor.' });
    if (action === 'bootstrap') return reply(200, { api, ok: true, csrf: state.csrf, data: { user: { ...state.user }, storage: { ...state.storage }, capabilities: { payroll: state.user.can_access_bordro }, catalog } });
    assert.equal(options.headers['X-VG-STAFF-CSRF'], state.csrf, 'Writes carry the real staff CSRF token');
    if (action === 'storage') {
      if (state.deferred) await state.deferred.promise;
      if (state.failure) return reply(503, { api, ok: false, error: 'storage_failed', message: state.failure });
      if (body.value === null) delete state.storage[body.key]; else state.storage[body.key] = body.value;
      return reply(200, { api, ok: true, data: null });
    }
    if (action === 'query') {
      if (body.filters.some(filter => filter.op === 'or')) return reply(400, { api, ok: false, error: 'invalid_filter', message: 'İfade desteklenmiyor.' });
      if (['update', 'delete'].includes(body.operation) && !body.filters.length) return reply(403, { api, ok: false, error: 'missing_predicate', message: 'Kaydın kimliği gerekir.' });
      if (body.table === 'conflict') return reply(409, { api, ok: false, error: 'PT409', message: 'Kayıt değişti.' });
      const rows = body.operation === 'select' ? [{ id: 'record-1', name: 'Test kaydı' }] : (Array.isArray(body.rows) ? body.rows : [body.rows]);
      return reply(200, { api, ok: true, data: body.single ? rows[0] : rows, count: rows.length });
    }
    if (action === 'rpc') return reply(200, { api, ok: true, data: { saved: true, ...body.args } });
    if (action === 'logout') { state.active = false; return reply(200, { api, ok: true, csrf: 'b'.repeat(64), user: null }); }
    if (action === 'forget_devices') {
      if (state.failure) return reply(503, { api, ok: false, error: 'unavailable', message: state.failure });
      state.active = false; return reply(200, { api, ok: true, csrf: 'c'.repeat(64), user: null });
    }
    throw new Error('Unknown fixture action');
  };
  const sdk = await import(pathToFileURL(path.resolve(__dirname, '../staff-app/src/supabaseClient.js')).href);
  const { privateStorage } = await import(pathToFileURL(path.resolve(__dirname, '../staff-app/src/privateStorage.js')).href);
  const initial = await sdk.initializePortal();
  check(initial.user.role, 'payroll', 'Actual staff role is preserved');
  check(initial.user.can_access_bordro, true, 'Payroll permission is server-provided');
  check(initial.catalog, catalog, 'Protected catalog passes to root initialization');
  check(privateStorage.getItem('favoriteProducts'), '["ilk"]', 'Server storage is hydrated before module reads');
  check(JSON.parse(privateStorage.getItem('currentUser')).id, state.user.id, 'Legacy identity read is server identity');
  check(privateStorage.length, 1, 'Identity is not a mutable preference entry');
  const session = await sdk.supabase.auth.getSession();
  check(session.data.session.user.id, state.user.id, 'Session exposes actual staff user');
  check('access_token' in session.data.session, false, 'No fake bearer token is created');
  check(sdk.adminSupabase === sdk.supabase, true, 'Legacy admin client is not privileged');
  check('SUPABASE_ANON_KEY' in sdk, false, 'No invented Supabase API key');
  const fakeLogin = await sdk.supabase.auth.setSession({ access_token: 'forged' });
  check(fakeLogin.error.code, 'unsupported_auth', 'Caller cannot install identity');
  check(sdk.getStaffIdentity().role, 'payroll', 'Forged session does not alter identity');
  await assert.rejects(sdk.supabase.auth.signUp().then(result => { if (result.error) throw result.error; }), /güvenli çalışan/); checks++;
  const query = sdk.supabase.from('products').select('id,name').eq('active', true).neq('id', 'old').gt('price', 1).gte('price', 2).lt('price', 100).lte('price', 99)
    .in('category', ['a', 'b']).is('deleted_at', null).not('user_id', 'is', null).order('created_at', { ascending: false }).order('id').limit(50).range(10, 19).maybeSingle();
  const first = await query;
  check(first.error, null, 'Thenable select returns ordinary result');
  check(first.data.id, 'record-1', 'Single result is retained');
  const wire = requests.at(-1).body;
  check(wire.single, 'maybe', 'Maybe-single contract serialized');
  check(wire.range, [10, 19], 'Inclusive pagination is serialized');
  check(wire.order, [{ field: 'created_at', ascending: false }, { field: 'id', ascending: true }], 'Multiple order fields retained');
  check(wire.filters.at(-1), { op: 'not', field: 'user_id', value: { op: 'is', value: null } }, 'Not-null contract matches PHP');
  check(wire.filters.length, 9, 'Every filter survives serialization');
  const countBefore = requests.length;
  await query;
  check(requests.length, countBefore, 'A thenable executes once');
  assert.throws(() => query.eq('id', 'later'), /Çalıştırılmış/); checks++;
  await sdk.supabase.from('products').insert({ name: 'Eklenen' }).select('id').single();
  check(requests.at(-1).body.rows, [{ name: 'Eklenen' }], 'Insert object normalizes to row array');
  check(requests.at(-1).body.returning, true, 'Mutation select requests returned rows');
  await sdk.supabase.from('monthly_payroll_summary').upsert([{ employee_id: 'test', month: 10, year: 2026 }], { onConflict: 'employee_id,month,year' });
  check(requests.at(-1).body.onConflict, 'employee_id,month,year', 'Composite upsert constraint survives');
  await sdk.supabase.from('products').update({ name: 'Düzenlenen' }).eq('id', 'record-1');
  check(requests.at(-1).body.rows, { name: 'Düzenlenen' }, 'Update remains an object');
  await sdk.supabase.from('products').delete().eq('id', 'record-1').select('id');
  check(requests.at(-1).body.operation, 'delete', 'Delete is explicit');
  check(requests.at(-1).body.filters[0].field, 'id', 'Delete preserves predicate');
  const unsafeDelete = await sdk.supabase.from('products').delete();
  check(unsafeDelete.error.code, 'missing_predicate', 'Server denial never becomes a successful fallback');
  const or = await sdk.supabase.from('products').or('role.eq.admin');
  check(or.error.code, 'invalid_filter', 'Unsupported raw expressions fail closed');
  const conflict = await sdk.supabase.from('conflict').select('*');
  check(conflict.error.status, 409, 'Concurrency status reaches module');
  check(conflict.error.code, 'PT409', 'Concurrency code reaches module');
  await sdk.supabase.rpc('app_company_document_save', { p_kind: 'teklif', p_expected_revision: 3 });
  check(requests.at(-1).body, { name: 'app_company_document_save', args: { p_kind: 'teklif', p_expected_revision: 3 } }, 'RPC and revision arguments serialized');
  const user = await sdk.supabase.auth.getUser();
  check(user.data.user.id, state.user.id, 'User lookup revalidates server profile');
  assert.throws(() => privateStorage.setItem('currentUser', '{"role":"admin"}'), /istemciden/); checks++;
  assert.throws(() => privateStorage.setItem('role', 'admin'), /istemciden/); checks++;
  assert.throws(() => privateStorage.setItem('session_token', 'forged'), /istemciden/); checks++;
  const bodyMaximum = 2097152, boundaryKey = 'sizeBoundary';
  const overhead = Buffer.byteLength(JSON.stringify({ key: boundaryKey, value: '' }));
  await privateStorage.setItem(boundaryKey, 'a'.repeat(bodyMaximum - overhead));
  check(Buffer.byteLength(requests.at(-1).options.body), bodyMaximum, 'Exact 2 MiB JSON request body is permitted');
  await privateStorage.removeItem(boundaryKey);
  const beforeOversize = requests.length;
  assert.throws(() => privateStorage.setItem(boundaryKey, 'a'.repeat(bodyMaximum - overhead + 1)), /2 MB/); checks++;
  check(requests.length, beforeOversize, 'Oversized value never queues an unsavable request');
  check(privateStorage.pending, 0, 'Oversized value does not become pending');
  check(privateStorage.getItem(boundaryKey), null, 'Oversized value does not alter memory');
  assert.throws(() => privateStorage.setItem(boundaryKey, '\u0000'.repeat(Math.floor((bodyMaximum - overhead) / 6) + 1)), /2 MB/); checks++;
  assert.throws(() => privateStorage.setItem(boundaryKey, 'ğ'.repeat(Math.floor((bodyMaximum - overhead) / 2) + 1)), /2 MB/); checks++;
  await privateStorage.setItem('favoriteProducts', '["ikinci"]');
  await privateStorage.flush();
  check(state.storage.favoriteProducts, '["ikinci"]', 'Memory preference is persisted per employee');
  check(privateStorage.pending, 0, 'Durability queue drains');
  await privateStorage.removeItem('favoriteProducts');
  check('favoriteProducts' in state.storage, false, 'Removing a value is a null write');
  state.failure = 'Özel sunucu kaydı başarısız.';
  await assert.rejects(privateStorage.setItem('savedQuotations', '[]'), /başarısız/); checks++;
  await assert.rejects(privateStorage.flush(), /başarısız/); checks++;
  check(privateStorage.getItem('savedQuotations'), '[]', 'Unsaved form state is retained in memory');
  check(privateStorage.pending, 1, 'Failed write stays pending');
  check(events.length > 0, true, 'Write failure is emitted for visible UI status');
  state.failure = null;
  await privateStorage.retry(); await privateStorage.flush();
  check(privateStorage.pending, 0, 'Retry clears dirty queue');
  let release;
  state.deferred = { promise: new Promise(resolve => { release = resolve; }) };
  const inFlight = privateStorage.setItem('savedQuotations', '["yeni"]');
  await new Promise(resolve => setTimeout(resolve, 0));
  state.storage.savedQuotations = '["sunucueski"]';
  await sdk.bootstrapCompany({ force: true });
  check(privateStorage.getItem('savedQuotations'), '["yeni"]', 'Bootstrap cannot overwrite an unsaved edit');
  release(); await inFlight; state.deferred = null;
  const requestsBeforeLogout = requests.length;
  const signOut = await sdk.supabase.auth.signOut();
  check(signOut.error, null, 'Logout uses independent staff endpoint');
  check(requests.at(-1).url, '/api/staff.php?action=logout', 'Logout never uses public membership');
  check(requests.length, requestsBeforeLogout + 1, 'Logout needs no bearer bridge');
  check(sdk.getStaffIdentity(), null, 'Logout erases client identity');
  check(privateStorage.length, 0, 'Logout erases private in-memory records');
  check(requests.every(request => request.options.credentials === 'same-origin' && request.options.cache === 'no-store'), true, 'Every request stays on same-origin HttpOnly sessions');
  check(requests.every(request => !('Authorization' in request.options.headers) && !('apikey' in request.options.headers)), true, 'No bearer, public API key or external endpoint is sent');
  check(requests.every(request => request.url.startsWith('/api/company.php') || request.url.startsWith('/api/staff.php')), true, 'All data stays on the private PHP endpoints');
  const expired = await sdk.supabase.auth.getSession();
  check(expired.data.session, null, 'Expired session cannot reconstruct employee identity');
  check(expired.error.status, 401, 'Expired status reaches caller');
  state.active = true; await sdk.initializePortal(); state.failure = 'Cihaz işlemi başarısız.';
  await assert.rejects(sdk.forgetRememberedDevices(), /başarısız/); checks++;
  check(sdk.getStaffIdentity().id, state.user.id, 'Failed device revocation keeps the current identity available for retry');
  state.failure = null; await sdk.forgetRememberedDevices();
  check(requests.at(-1).url, '/api/staff.php?action=forget_devices', 'Device revocation uses the CSRF-protected employee endpoint');
  check(requests.at(-1).options.headers['X-VG-STAFF-CSRF'], state.csrf, 'Device revocation carries the current employee CSRF');
  check(sdk.getStaffIdentity(), null, 'Successful revocation clears the current identity');
  check(privateStorage.length, 0, 'Successful revocation clears private in-memory records');
  console.log(`Company client: ${checks} checks passed; fixtures isolated from all real staff data.`);
})().catch(error => { console.error(error.message); process.exitCode = 1; });
